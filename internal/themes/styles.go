// A reader chooses a style in gsxui's theme editor as they choose a colour, and the app is drawn in it. gsxui has a
// style in the components themselves: the same component in another style is other markup. So an app has its
// components in each of gsxui's styles: its own in ui, as gsxui add and gsxui apply keep them, and each other in
// ui/styles/<style>, written here by gsxui's own apply (run in a copy of the app, so it writes them as it would
// into the app: for the app's module, right to left where the app is). Beside them, ui/styles itself is a package
// named ui with every component of the app's: each renders the reader's style (app.Style). Pages import it where
// they would import ui.
//
// One thing stays the app's own style whatever is chosen: a component that takes a type of its own package (a
// chart's ChartConfig), which no other package's component can be handed.
const (
	stylesDir = "ui/styles"
	styled    = "styles.gen.go"
	expected  = "expected.gen.go"
	// generator is raised when what this file writes changes, so every app's is written again.
	generator = "1"
)

// StylesImport is the import path of the package pages take their components from, in the app in dir.
func StylesImport(dir string) string {
	mod, _ := modulePath(dir)
	return mod + "/" + stylesDir
}

// WriteStyles writes the app's components in every style of gsxui's but its own, and the package that chooses
// among them, when what is there is not what the app's gsxui, its own style and its components give; with check
// it writes nothing and fails then. An app with no gsxui has none.
func WriteStyles(dir string, check bool) error {
	raw, err := os.ReadFile(filepath.Join(dir, "gsxui.preset.json"))
	if os.IsNotExist(err) {
		return nil
	} else if err != nil {
		return err
	}
	var preset struct{ Style string }
	if err := json.Unmarshal(raw, &preset); err != nil {
		return fmt.Errorf("gsxui.preset.json: %w", err)
	}
	if !slices.Contains(Styles, preset.Style) {
		return fmt.Errorf("gsxui.preset.json: %q is no style of gsxui's that this charter knows (%s)", preset.Style, strings.Join(Styles, ", "))
	}
	sources, err := filepath.Glob(filepath.Join(dir, "ui", "*.gsx"))
	if err != nil {
		return err
	}
	sort.Strings(sources)
	var names []string
	for _, s := range sources {
		names = append(names, filepath.Base(s))
	}
	config, _ := os.ReadFile(filepath.Join(dir, "gsxui.json"))
	var settings struct{ RTL bool }
	_ = json.Unmarshal(config, &settings)
	out, err := exec.Command("go", "list", "-C", dir, "-m", "-f", "{{.Version}}", "github.com/gsxhq/gsxui").Output()
	if err != nil {
		return fmt.Errorf("the app's gsxui: %w", err)
	}
	mod, err := modulePath(dir)
	if err != nil {
		return err
	}
	var others []string
	for _, s := range Styles {
		if s != preset.Style {
			others = append(others, s)
		}
	}
	// The package that chooses is from the app's own components as they are now: a component the app changed
	// (another parameter) changes it.
	choosing, err := chooser(dir, mod, sources, others)
	if err != nil {
		return err
	}
	key := fmt.Sprintf("%x", sha256.Sum256([]byte(strings.Join([]string{generator, strings.TrimSpace(string(out)), preset.Style, strings.Join(names, ","), fmt.Sprint(settings.RTL), choosing}, "\x00"))))[:16]
	target := filepath.Join(dir, filepath.FromSlash(stylesDir))
	if old, err := os.ReadFile(filepath.Join(target, styled)); err == nil {
		if m := keyed.FindSubmatch(old); m != nil && string(m[1]) == key && stylesPresent(target, others, names) {
			return nil
		}
	}
	if check {
		return fmt.Errorf("the app's components in gsxui's other styles (%s) are not what its gsxui, its own style and its components give: charter check --fix writes them", stylesDir)
	}
	files, err := inEveryStyle(dir, others, names)
	if err != nil {
		return err
	}
	if err := os.RemoveAll(target); err != nil {
		return err
	}
	files[styled] = "// Code generated by charter check --fix from " + key + ": the app's components (ui), each rendering in the gsxui style the\n" +
		"// reader chose in the theme editor (app.Style). DO NOT EDIT: change a component in ui, or the app's style with\n" +
		"// charter run ui:theme.\n\n" + choosing
	for rel, text := range files {
		file := filepath.Join(target, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(file, []byte(text), 0o644); err != nil {
			return err
		}
	}
	fmt.Printf("%s: the app's %d components in gsxui's %s, beside its own %s\n", stylesDir, len(names), strings.Join(others, ", "), preset.Style)
	return nil
}

func stylesPresent(target string, styles, names []string) bool {
	for _, s := range styles {
		for _, n := range names {
			if _, err := os.Stat(filepath.Join(target, s, n)); err != nil {
				return false
			}
		}
	}
	if _, err := os.Stat(filepath.Join(target, expected)); err == nil {
		return false
	}
	entries, _ := os.ReadDir(target)
	dirs := 0
	for _, e := range entries {
		if e.IsDir() {
			dirs++
		}
	}
	return dirs == len(styles)
}

// inEveryStyle is the app's components in each of styles, as gsxui's own apply writes them: it is run in a copy of
// the app that has its components and nothing that uses them, once for each style, and what it wrote is taken
// with the package's name changed to the style's.
func inEveryStyle(dir string, styles, names []string) (map[string]string, error) {
	work, err := os.MkdirTemp("", "charter-styles-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(work)
	skip := map[string]bool{"node_modules": true, "build": true, "dist": true, ".wrangler": true, ".charter": true, ".git": true}
	err = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		if d.IsDir() {
			if (skip[d.Name()] && rel != ".") || filepath.ToSlash(rel) == stylesDir {
				return filepath.SkipDir
			}
			return os.MkdirAll(filepath.Join(work, rel), 0o755)
		}
		// A page uses the components through ui/styles, which is not written yet: gsxui's apply generates the Go
		// of every template it finds, so only the components' own are there.
		inUI := strings.HasPrefix(filepath.ToSlash(rel), "ui/")
		if !d.Type().IsRegular() || strings.HasSuffix(rel, ".x.go") || (strings.HasSuffix(rel, ".gsx") && !inUI) {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(work, rel), b, 0o644)
	})
	if err != nil {
		return nil, err
	}
	if err := absoluteReplaces(dir, work); err != nil {
		return nil, err
	}
	files := map[string]string{}
	for _, style := range styles {
		code, err := Code(style, Bases[0], Bases[0])
		if err != nil {
			return nil, err
		}
		cmd := exec.Command("go", "tool", "gsxui", "apply", "--preset", code, "--only", "style", "--yes", "--overwrite")
		cmd.Dir = work
		if out, err := cmd.CombinedOutput(); err != nil {
			return nil, fmt.Errorf("gsxui apply, for the app's components in %s: %w\n%s", style, err, out)
		}
		for _, name := range names {
			b, err := os.ReadFile(filepath.Join(work, "ui", name))
			if err != nil {
				return nil, err
			}
			if !packageUI.Match(b) {
				return nil, fmt.Errorf("gsxui's %s in %s is no longer of package ui: this charter does not know this gsxui", name, style)
			}
			files[style+"/"+name] = "// Written by charter check --fix: gsxui's " + style + " of ui/" + name + ", as gsxui apply writes it. Do not edit: a reader who\n// chooses " + style + " in the theme editor is shown it.\n\n" +
				string(packageUI.ReplaceAll(b, []byte("package "+style)))
		}
	}
	return files, nil
}

var packageUI = regexp.MustCompile(`(?m)^package ui$`)

// absoluteReplaces points the copy's go.mod at what the app's points at beside itself (charter, in this
// repository; an SDK of the app's own), which is not beside the copy.
func absoluteReplaces(dir, work string) error {
	list := exec.Command("go", "mod", "edit", "-json")
	list.Dir = dir
	out, err := list.Output()
	if err != nil {
		return err
	}
	var mod struct {
		Replace []struct {
			Old struct{ Path, Version string }
			New struct{ Path, Version string }
		}
	}
	if err := json.Unmarshal(out, &mod); err != nil {
		return err
	}
	for _, r := range mod.Replace {
		if r.New.Version != "" || filepath.IsAbs(r.New.Path) {
			continue
		}
		abs, err := filepath.Abs(filepath.Join(dir, r.New.Path))
		if err != nil {
			return err
		}
		old := r.Old.Path
		if r.Old.Version != "" {
			old += "@" + r.Old.Version
		}
		edit := exec.Command("go", "mod", "edit", "-replace", old+"="+abs)
		edit.Dir = work
		if out, err := edit.CombinedOutput(); err != nil {
			return fmt.Errorf("go mod edit: %w\n%s", err, out)
		}
	}
	return nil
}

var (
	component = regexp.MustCompile(`(?m)^component ([A-Z]\w*)\((.*)\) \{$`)
	function  = regexp.MustCompile(`(?m)^func ([A-Z]\w*)\((.*)\) gsx\.Node \{$`)
	otherFunc = regexp.MustCompile(`(?m)^func ([A-Z]\w*)\(`)
	declared  = regexp.MustCompile(`(?m)^type ([A-Z]\w*) `)
	ownType   = regexp.MustCompile(`(^|[^.\w])[A-Z]\w*`)
	qualifier = regexp.MustCompile(`\b([a-z]\w*)\.[A-Z]`)
)

// What a component's parameters may be of and still be handed to another style's: these packages' types.
var known = map[string]string{"gsx": "github.com/gsxhq/gsx", "time": "time"}

// chooser is the Go of ui/styles: for each component of the app's own (ui/*.gsx), one of the same name and
// parameters that renders the reader's style of it.
func chooser(dir, module string, sources, styles []string) (string, error) {
	var body bytes.Buffer
	imports := map[string]bool{"github.com/gsxhq/gsx": true}
	seen := map[string]bool{}
	for _, source := range sources {
		b, err := os.ReadFile(source)
		if err != nil {
			return "", err
		}
		text := string(b)
		for _, m := range declared.FindAllStringSubmatch(text, -1) {
			fmt.Fprintf(&body, "type %s = own.%s\n\n", m[1], m[1])
		}
		for _, m := range slices.Concat(component.FindAllStringSubmatch(text, -1), function.FindAllStringSubmatch(text, -1)) {
			name, params := m[1], m[2]
			seen[name] = true
			args, ok := arguments(params, imports)
			if !ok {
				// It takes a type of its own package: the app's own style, whatever is chosen.
				fmt.Fprintf(&body, "// %s takes a type of its own package, which another style's cannot be handed: it is the app's own style's.\nvar %s = own.%s\n\n", name, name, name)
				continue
			}
			fmt.Fprintf(&body, "func %s(%s) gsx.Node {\n\treturn gsx.Func(func(ctx context.Context, w io.Writer) error {\n\t\tswitch app.Style(ctx) {\n", name, params)
			for _, style := range styles {
				fmt.Fprintf(&body, "\t\tcase %q:\n\t\t\treturn %s.%s(%s).Render(ctx, w)\n", style, style, name, args)
			}
			fmt.Fprintf(&body, "\t\t}\n\t\treturn own.%s(%s).Render(ctx, w)\n\t})\n}\n\n", name, args)
		}
		for _, m := range otherFunc.FindAllStringSubmatch(text, -1) {
			if !seen[m[1]] {
				seen[m[1]] = true
				fmt.Fprintf(&body, "var %s = own.%s\n\n", m[1], m[1])
			}
		}
	}
	if len(seen) == 0 {
		return "", errors.New("ui has no component this charter can read (component Name(...) {): this charter does not know this gsxui")
	}
	var head bytes.Buffer
	head.WriteString("package ui\n\nimport (\n\t\"context\"\n\t\"io\"\n")
	std, rest := []string{}, []string{}
	for path := range imports {
		if strings.Contains(path, ".") {
			rest = append(rest, path)
		} else {
			std = append(std, path)
		}
	}
	sort.Strings(std)
	for _, path := range std {
		fmt.Fprintf(&head, "\t%q\n", path)
	}
	head.WriteString("\n")
	rest = append(rest, "github.com/joeblew999/charter/app")
	sort.Strings(rest)
	for _, path := range rest {
		fmt.Fprintf(&head, "\t%q\n", path)
	}
	fmt.Fprintf(&head, "\n\town %q\n", module+"/ui")
	for _, style := range styles {
		fmt.Fprintf(&head, "\t%q\n", module+"/"+stylesDir+"/"+style)
	}
	head.WriteString(")\n\n")
	return head.String() + strings.TrimRight(body.String(), "\n") + "\n", nil
}

// arguments is the names of params, to call another component of the same parameters with, and whether every one
// is of a type another package's component takes too. It notes the packages the types are from.
func arguments(params string, imports map[string]bool) (string, bool) {
	if strings.TrimSpace(params) == "" {
		return "", true
	}
	var names []string
	for _, p := range strings.Split(params, ", ") {
		name, kind, ok := strings.Cut(p, " ")
		if !ok || ownType.MatchString(kind) {
			return "", false
		}
		for _, q := range qualifier.FindAllStringSubmatch(kind, -1) {
			path, ok := known[q[1]]
			if !ok {
				return "", false
			}
			imports[path] = true
		}
		if strings.HasPrefix(kind, "...") {
			name += "..."
		}
		names = append(names, name)
	}
	return strings.Join(names, ", "), true
}

// modulePath is the app's module, from its own go.mod (go list -m names every module of a workspace).
func modulePath(dir string) (string, error) {
	cmd := exec.Command("go", "mod", "edit", "-json")
	cmd.Dir = dir
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	var mod struct{ Module struct{ Path string } }
	if err := json.Unmarshal(out, &mod); err != nil {
		return "", err
	}
	return mod.Module.Path, nil
}

// Unstyled lists the app's templates that take their components from ui itself, where they are the app's own style
// whatever a reader chose: file and line, for charter check. Templates inside ui are the components.
func Unstyled(dir string) ([]string, error) {
	if _, err := os.Stat(filepath.Join(dir, filepath.FromSlash(stylesDir), styled)); err != nil {
		return nil, nil
	}
	mod, err := modulePath(dir)
	if err != nil {
		return nil, err
	}
	direct := []byte(`"` + mod + `/ui"`)
	var found []string
	err = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		if d.IsDir() {
			if rel != "." && (strings.HasPrefix(d.Name(), ".") || d.Name() == "node_modules" || d.Name() == "ui" || d.Name() == "build" || d.Name() == "dist") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(rel, ".gsx") {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for i, line := range bytes.Split(b, []byte("\n")) {
			if bytes.Contains(line, direct) {
				found = append(found, fmt.Sprintf("%s:%d", filepath.ToSlash(rel), i+1))
			}
		}
		return nil
	})
	return found, err
}

// Expect has ui/styles declare the components gsxui add is about to bring (names, as gsxui add takes them), before
// it does. gsxui add generates the Go of every template of the app as it finishes and takes back what it added
// when that fails; a page that already uses a new component takes it from ui/styles, which only has it once the
// component is there. So each is declared first, rendering nothing, from gsxui's own source of it, and WriteStyles,
// after gsxui add, writes the package as it is to be. An app with no ui/styles needs none of it.
func Expect(dir string, names []string) error {
	target := filepath.Join(dir, filepath.FromSlash(stylesDir))
	if _, err := os.Stat(filepath.Join(target, styled)); err != nil || len(names) == 0 {
		return nil
	}
	raw, err := os.ReadFile(filepath.Join(dir, "gsxui.preset.json"))
	if err != nil {
		return err
	}
	var preset struct{ Style string }
	if err := json.Unmarshal(raw, &preset); err != nil {
		return err
	}
	out, err := exec.Command("go", "list", "-C", dir, "-m", "-f", "{{.Dir}}", "github.com/gsxhq/gsxui").Output()
	if err != nil {
		return fmt.Errorf("the app's gsxui: %w", err)
	}
	var body bytes.Buffer
	imports := map[string]bool{"github.com/gsxhq/gsx": true}
	for _, name := range names {
		b, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), "registry", "generated", preset.Style, name+".gsx"))
		if err != nil {
			continue // a folder of them (icon), or one gsxui add will say it does not have
		}
		for _, m := range slices.Concat(component.FindAllStringSubmatch(string(b), -1), function.FindAllStringSubmatch(string(b), -1)) {
			if _, ok := arguments(m[2], imports); ok {
				fmt.Fprintf(&body, "func %s(%s) gsx.Node { return nil }\n\n", m[1], m[2])
			}
		}
	}
	if body.Len() == 0 {
		return nil
	}
	head := "// Code generated by charter, while gsxui add brings these components: what ui/styles is to have of them, rendering\n// nothing. charter writes the package as it is to be when gsxui add is done (charter check --fix does too).\n\npackage ui\n\nimport (\n"
	paths := []string{}
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		head += fmt.Sprintf("\t%q\n", path)
	}
	return os.WriteFile(filepath.Join(target, expected), []byte(head+")\n\n"+strings.TrimRight(body.String(), "\n")+"\n"), 0o644)
}

// OwnShells lists the app's templates that write a document of their own (<!DOCTYPE html>) where the app has
// charter's layout screen (pages/screens/layout.gsx), which is the one document around every page: file and line,
// for charter check. A page in a shell of its own sets its own widths and header, and is the page that does not
// fit a phone.
func OwnShells(dir string) ([]string, error) {
	layout := filepath.Join("pages", "screens", "layout.gsx")
	if _, err := os.Stat(filepath.Join(dir, layout)); err != nil {
		return nil, nil
	}
	var found []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		if d.IsDir() {
			if rel != "." && (strings.HasPrefix(d.Name(), ".") || d.Name() == "node_modules" || d.Name() == "ui" || d.Name() == "build" || d.Name() == "dist") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(rel, ".gsx") || rel == layout {
			return nil
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		for i, line := range bytes.Split(b, []byte("\n")) {
			if bytes.Contains(bytes.ToLower(line), []byte("<!doctype html>")) {
				found = append(found, fmt.Sprintf("%s:%d", filepath.ToSlash(rel), i+1))
			}
		}
		return nil
	})
	return found, err
}
