// A project's database code, from its schema (db.ts): the Drizzle tables as SQLite has them once the
// migrations ran, and the Go queries from what sqlc worked out (here written by hand, as sqlc gives it).
//   node --test src/*.test.ts   (npm run check -w charter-ts runs them)
import assert from "node:assert/strict";
import { it } from "node:test";
import { drizzleTables, goQueries, type SqlcRequest } from "./db.ts";

it("writes each table as Drizzle has it: keys, NOT NULL, UNIQUE, defaults, the last migration's shape", () => {
	const ts = drizzleTables([
		"CREATE TABLE notes (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP);",
		"CREATE TABLE tags (note_id INTEGER NOT NULL, name TEXT NOT NULL UNIQUE, weight REAL, PRIMARY KEY (note_id, name));",
		// A later migration changes a table: what counts is the schema once all ran.
		"CREATE TABLE notes_new (id INTEGER PRIMARY KEY AUTOINCREMENT, body TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP); DROP TABLE notes; ALTER TABLE notes_new RENAME TO notes;",
	]);
	assert.match(ts, /^\/\/ Written by `charter-ts spec`/);
	assert.match(ts, /import \{ integer, primaryKey, real, sqliteTable, text \} from "drizzle-orm\/sqlite-core";/);
	assert.match(ts, /export const notes = sqliteTable\("notes", \{\n\tid: integer\("id"\)\.primaryKey\(\{ autoIncrement: true \}\),\n\tbody: text\("body"\)\.notNull\(\),\n\tcreated_at: text\("created_at"\)\.notNull\(\)\.default\(sql`CURRENT_TIMESTAMP`\),\n\}\);/);
	assert.match(ts, /\tname: text\("name"\)\.notNull\(\)\.unique\(\),/);
	assert.match(ts, /\}, table => \[primaryKey\(\{ columns: \[table\["note_id"\], table\["name"\]\] \}\)\]\);/);
});

const column = (name: string, type: string, not_null = true, table: string | null = "notes") => ({ name, not_null, type: { name: type }, table: table ? { name: table } : null });

it("writes each query as a typed Go function over charter/d1", () => {
	const request: SqlcRequest = {
		catalog: { schemas: [{ tables: [{ rel: { name: "notes" }, columns: [column("id", "INTEGER"), column("body", "TEXT"), column("created_at", "TEXT", false)] }] }] },
		queries: [
			{ name: "CreateNote", cmd: ":one", text: "\nINSERT INTO notes (body) VALUES (?) RETURNING id, body, created_at", comments: [" The file's own comment"], columns: [column("id", "INTEGER"), column("body", "TEXT"), column("created_at", "TEXT", false)], params: [{ number: 1, column: column("body", "TEXT") }] },
			{ name: "Bodies", cmd: ":many", text: "SELECT body FROM notes WHERE created_at > ?", comments: [" Bodies is every note's body after a time."], columns: [column("body", "TEXT")], params: [{ number: 1, column: column("created_at", "TEXT", false) }] },
			{ name: "Stamp", cmd: ":exec", text: "UPDATE notes SET created_at = ? WHERE id = ?", columns: [], params: [{ number: 1, column: column("created_at", "TEXT", false) }, { number: 2, column: column("id", "INTEGER") }] },
		],
	};
	const go = goQueries(request, "api");
	assert.match(go, /^\/\/ Code generated by charter-ts spec .* DO NOT EDIT\.$/m);
	assert.match(go, /\/\/go:build js && wasm\n\npackage api\n/);
	// A row of the whole table is the table's type; a column that may be NULL, a pointer.
	assert.match(go, /type NotesRow struct \{\n\tID +int64 +`json:"id"`\n\tBody +string +`json:"body"`\n\tCreatedAt \*string `json:"created_at"`\n\}/);
	// The file's own comment is not a query's doc; one that names the query is.
	assert.match(go, /\/\/ CreateNote runs the query CreateNote of api\/queries.sql.\nfunc CreateNote\(db d1.DB, body string\) \(NotesRow, error\) \{\n\treturn d1.One\[NotesRow\]\(db, qCreateNote, body\)\n\}/);
	assert.match(go, /const qCreateNote = "INSERT INTO notes/);
	// One column: its values; a nullable argument goes as NULL when nil.
	assert.match(go, /\/\/ Bodies is every note's body after a time.\nfunc Bodies\(db d1.DB, createdAt \*string\) \(\[\]string, error\) \{\n\trows, err := d1.Query\[BodiesRow\]\(db, qBodies, d1.OrNull\(createdAt\)\)/);
	assert.match(go, /func Stamp\(db d1.DB, createdAt \*string, id int64\) error \{\n\treturn d1.Exec\(db, qStamp, d1.OrNull\(createdAt\), id\)\n\}/);
});

it("refuses what it does not write", () => {
	const request = (cmd: string): SqlcRequest => ({ catalog: { schemas: [] }, queries: [{ name: "Count", cmd, text: "SELECT 1", columns: [column("n", "integer", true, null)], params: [] }] });
	assert.throws(() => goQueries(request(":execrows"), "api"), /:one, :many and :exec/);
});
